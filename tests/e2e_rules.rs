//! E2E tests for each lint rule's detection logic.

mod common;

use common::write_ts_file;
use predicates::prelude::*;

#[test]
fn detects_nested_ternary_violation() {
    let (_dir, path) = write_ts_file("ternary.ts", "export const x = a ? b ? 1 : 2 : 3;\n");
    common::comply()
        .arg(&path)
        .assert()
        .stdout(predicate::str::contains("no-nested-ternary"));
}

#[test]
fn detects_banned_identifier() {
    let (_dir, path) = write_ts_file("banned.ts", "function processOrder() { return 1; }\n");
    common::comply()
        .arg(&path)
        .assert()
        .stdout(predicate::str::contains("no-generic-names"))
        .stdout(predicate::str::contains("processOrder"));
}

#[test]
fn detects_nested_ternary() {
    let (_dir, path) = write_ts_file("ternary.ts", "const x = a ? b ? 1 : 2 : 3;\n");
    common::comply()
        .arg(&path)
        .assert()
        .stdout(predicate::str::contains("no-nested-ternary"));
}

#[test]
fn multiple_violations_are_all_reported() {
    let source = "function processOrder() { const y = a ? b ? 1 : 2 : 3; }\n";
    let (_dir, path) = write_ts_file("multi.ts", source);
    common::comply()
        .arg(&path)
        .assert()
        .code(1)
        .stdout(predicate::str::contains("no-nested-ternary"))
        .stdout(predicate::str::contains("no-generic-names"));
}

#[test]
fn nginx_add_header_without_always_is_reported_only_in_nginx_files() {
    let dir = tempfile::TempDir::new().unwrap();
    for sub in ["nginx", "app"] {
        std::fs::create_dir(dir.path().join(sub)).unwrap();
        std::fs::write(
            dir.path().join(sub).join("site.conf"),
            "add_header X DENY;\n",
        )
        .unwrap();
    }
    common::comply()
        .arg(dir.path())
        .assert()
        .stdout(predicate::str::contains("nginx-add-header-always"))
        .stdout(predicate::str::contains("nginx/site.conf"))
        .stdout(predicate::str::contains("app/site.conf").not());
}

#[test]
fn homemade_async_state_is_reported() {
    let source = "export type Status = \"idle\" | \"loading\" | \"error\";\n";
    let (_dir, path) = write_ts_file("status.ts", source);
    common::comply()
        .arg(&path)
        .assert()
        .stdout(predicate::str::contains("no-homemade-async-state-union"));
}

#[test]
fn homemade_async_state_is_skipped_in_a_generated_file() {
    // The engine drops generated files before any rule runs; this pins that
    // the rule inherits that exemption rather than re-implementing it.
    let source = "// @generated by openapi-typescript\nexport type Status = \"idle\" | \"loading\";\n";
    let (_dir, path) = write_ts_file("generated-status.ts", source);
    common::comply()
        .arg(&path)
        .assert()
        .stdout(predicate::str::contains("no-homemade-async-state-union").not());
}

#[test]
fn module_dependencies_skips_test_files() {
    let dir = tempfile::TempDir::new().expect("temp dir");
    let comply_toml = "[rules.module-dependencies]\nroot = \"src\"\n\n\
        [rules.module-dependencies.modules]\nfailure = []\nlanguage = []\n";
    let import = "import { c } from '../language/c';\n";
    for (rel, source) in [
        ("comply.toml", comply_toml),
        ("src/language/c.ts", "export const c = 1;\n"),
        ("src/failure/a.ts", import),
        ("src/failure/a.test.ts", import),
    ] {
        let path = dir.path().join(rel);
        std::fs::create_dir_all(path.parent().expect("parent")).expect("create dir");
        std::fs::write(path, source).expect("write fixture");
    }
    common::comply()
        .args(["rules", "module-dependencies"])
        .arg(dir.path())
        .assert()
        .stdout(predicate::str::contains("a.ts"))
        .stdout(predicate::str::contains("a.test.ts").not());
}

/// Breaks the three opt-in rules and holds a raw NBSP.
const FRENCH_PAGE: &str =
    "export const Page = () => <p>Attention : l'agent d\u{e9}sol\u{e9} a\u{a0}b</p>;\n";

#[test]
fn french_copy_rules_are_off_by_default() {
    let (dir, path) = write_ts_file("Page.tsx", FRENCH_PAGE);
    common::config_without_type_aware_rules(
        dir.path(),
        "[rules.banned-copy-words]\nbanned = [\"d\u{e9}sol\u{e9}\"]\n",
    );
    common::comply()
        .current_dir(dir.path())
        .arg(&path)
        .assert()
        .stdout(predicate::str::contains("no-raw-invisible-character"))
        .stdout(predicate::str::contains("french-nbsp-before-punctuation").not())
        .stdout(predicate::str::contains("banned-copy-words").not())
        .stdout(predicate::str::contains("copy-apostrophe-style").not());
}

#[test]
fn french_copy_rules_report_once_enabled() {
    let (dir, path) = write_ts_file("Page.tsx", FRENCH_PAGE);
    common::config_without_type_aware_rules(
        dir.path(),
        "[rules.french-nbsp-before-punctuation]\ndisabled = false\n\
         [rules.banned-copy-words]\ndisabled = false\nbanned = [\"d\u{e9}sol\u{e9}\"]\n\
         [rules.copy-apostrophe-style]\ndisabled = false\n",
    );
    common::comply()
        .current_dir(dir.path())
        .arg(&path)
        .assert()
        .stdout(predicate::str::contains("french-nbsp-before-punctuation"))
        .stdout(predicate::str::contains("banned-copy-words"))
        .stdout(predicate::str::contains("copy-apostrophe-style"));
}

const RUNTIME_IDIOM_RULES: &[&str] = &[
    "no-conditional-empty-object-spread",
    "no-reduce-accumulator-copy",
    "no-reflect-apply",
    "require-explicit-time-zone",
    "no-escape-in-jsx-text",
    "no-native-title",
];

const RUNTIME_IDIOM_SOURCE: &str = r#"export const pair = items.filter(f).map(g);
export const single = items.map(g);
export const spread = { ...(cond ? { k } : {}) };
export const copied = items.reduce((acc, x) => acc.concat(x), []);
export const applied = Reflect.apply(f, t, args);
export const day = date.toLocaleDateString("fr");
export const text = <p>a\u00A0b</p>;
export const titled = <span title="x">t</span>;
"#;

const RUNTIME_IDIOM_CONFIG: &str = r#"[rules.no-conditional-empty-object-spread]
disabled = false
[rules.no-reduce-accumulator-copy]
disabled = false
[rules.no-reflect-apply]
disabled = false
[rules.require-explicit-time-zone]
disabled = false
[rules.no-escape-in-jsx-text]
disabled = false
[rules.no-native-title]
disabled = false
hint = "<Tooltip>"
[rules.react-no-chained-filter-map-reduce]
min_chain = 2
[rules.testing-no-mocking-internal-modules]
include_packages = true
"#;

#[test]
fn runtime_idiom_rules_are_opt_in_and_configurable() {
    let dir = tempfile::TempDir::new().unwrap();
    common::without_type_aware_rules(dir.path());
    let write = |name: &str, content: &str| std::fs::write(dir.path().join(name), content).unwrap();
    write(
        "package.json",
        r#"{"name":"t","version":"0.0.0","dependencies":{"react":"^18.0.0"}}"#,
    );
    write("list.tsx", RUNTIME_IDIOM_SOURCE);
    write(
        "api.test.ts",
        "vi.mock(\"axios\");\njest.mock(\"axios\");\nvi.doMock(\"axios\");\njest.unstable_mockModule(\"axios\", () => ({}));\n",
    );
    let lint = || {
        let output = common::comply().arg(dir.path()).output().unwrap();
        String::from_utf8(output.stdout).unwrap()
    };
    let lines_of = |stdout: &str, id: &str| stdout.lines().filter(|line| line.contains(id)).count();

    let stock = lint();
    for id in RUNTIME_IDIOM_RULES.iter().chain(&[
        "react-no-chained-filter-map-reduce",
        "testing-no-mocking-internal-modules",
    ]) {
        assert!(!stock.contains(id), "{id} fired without opt-in:\n{stock}");
    }

    common::config_without_type_aware_rules(dir.path(), RUNTIME_IDIOM_CONFIG);
    let configured = lint();
    for id in RUNTIME_IDIOM_RULES {
        assert!(
            configured.contains(id),
            "{id} did not fire once enabled:\n{configured}"
        );
    }
    assert!(
        configured.contains("<Tooltip>"),
        "hint missing:\n{configured}"
    );
    assert_eq!(
        lines_of(&configured, "react-no-chained-filter-map-reduce"),
        1,
        "{configured}"
    );
    assert_eq!(
        lines_of(&configured, "testing-no-mocking-internal-modules"),
        4,
        "{configured}"
    );
}
